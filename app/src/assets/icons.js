/**
 * Get an SVG icon by name
 * @param {string} name - Icon name
 * @param {Object} options - Icon options
 * @returns {string} SVG HTML string
 */
export function getIcon(name, options = {}) {
  const {
    className = '',
    width = '24',
    height = '24',
    color = 'currentColor'
  } = options

  const iconSvg = icons[name]
  if (!iconSvg) {
    console.warn(`Icon "${name}" not found`)
    return ''
  }

  // Add class and dimensions to SVG
  return iconSvg
    .replace('<svg', `<svg class="${className}" width="${width}" height="${height}"`)
    .replace(/currentColor/g, color)
}

/**
 * Create an icon element
 * @param {string} name - Icon name
 * @param {Object} options - Icon options
 * @returns {HTMLElement} Icon element
 */
export function createIcon(name, options = {}) {
  const wrapper = document.createElement('span')
  wrapper.className = `icon-wrapper ${options.wrapperClass || ''}`
  wrapper.innerHTML = getIcon(name, options)
  return wrapper
}

export default icons
